function runGeometry(payload) {
  return new Promise((resolve, reject) => {
    const child = spawn("python3", ["scripts/braid_geometry.py"], {
      cwd: process.cwd(),
      stdio: ["pipe", "pipe", "pipe"]
    });
    const stdout = [];
    const stderr = [];
    child.stdout.on("data", (chunk) => stdout.push(chunk));
    child.stderr.on("data", (chunk) => stderr.push(chunk));
    child.on("error", reject);
    child.on("close", (code) => {
      const errorText = Buffer.concat(stderr).toString("utf8");
      if (code !== 0) return reject(new Error(errorText || `Geometry exited ${code}`));
      const serialized = Buffer.concat(stdout);
      const result = JSON.parse(serialized.toString("utf8"));
      Object.defineProperty(result, "serializedBytes", { value: serialized.byteLength });
      resolve(result);
    });
    child.stdin.end(JSON.stringify(payload));
  });
}

function runDimensions(payload) {
  return new Promise((resolve, reject) => {
    const child = spawn("python3", [
      "-c",
      "import json,sys; from scripts.braid_geometry import carrier_dimensions; print(json.dumps(carrier_dimensions(json.load(sys.stdin))))"
    ], {
      cwd: process.cwd(),
      stdio: ["pipe", "pipe", "pipe"]
    });
    const stdout = [];
    const stderr = [];
    child.stdout.on("data", (chunk) => stdout.push(chunk));
    child.stderr.on("data", (chunk) => stderr.push(chunk));
    child.on("error", reject);
    child.on("close", (code) => {
      if (code !== 0) return reject(new Error(Buffer.concat(stderr).toString("utf8")));
      resolve(JSON.parse(Buffer.concat(stdout).toString("utf8")));
    });
    child.stdin.end(JSON.stringify(payload));
  });
}

function basePayload() {
  return {
    carrierCount: 16,
    diameterMm: 16,
    braidAngle: 34,
    strandWidthScale: 1,
    filamentCount: 25,
    denier: 1000,
    denierScale: 0.7,
    crossingMode: "diamond",
    visibleRows: 8,
    carriers: Array.from({ length: 16 }, (_, index) => ({
      no: index + 1,
      color: [0, 2].includes(index) ? "#e11912" : "#f6f5ee"
    }))
  };
}

function median(values) {
  const ordered = [...values].sort((left, right) => left - right);
  return ordered[Math.floor(ordered.length / 2)];
}

function measuredMeshAngle(yarn, ringSegments, radius) {
  const values = [];
  let previous = null;
  for (let ring = 0; ring < yarn.pathPointCount; ring += 1) {
    const offset = (ring * ringSegments + Math.floor(ringSegments / 2)) * 3;
    const current = {
      x: yarn.mesh.vertices[offset],
      theta: Math.atan2(yarn.mesh.vertices[offset + 2], yarn.mesh.vertices[offset + 1])
    };
    if (previous) {
      let deltaTheta = current.theta - previous.theta;
      while (deltaTheta > Math.PI) deltaTheta -= Math.PI * 2;
      while (deltaTheta < -Math.PI) deltaTheta += Math.PI * 2;
      values.push(
        Math.atan(Math.abs(radius * deltaTheta / (current.x - previous.x))) * 180 / Math.PI
      );
    }
    previous = current;
  }
  return median(values);
}

function interiorRunLengths(values) {
  const runs = [];
  for (const value of values) {
    const last = runs.at(-1);
    if (last?.value === value) last.length += 1;
    else runs.push({ value, length: 1 });
  }
  return runs.slice(1, -1).map((run) => run.length);
}

test("crossing proof and rope are generated by one geometry contract", async () => {
  const payload = basePayload();
  const [rope, crossing] = await Promise.all([
    runGeometry({ ...payload, mode: "rope" }),
    runGeometry({ ...payload, mode: "crossing" })
  ]);

  assert.equal(rope.geometryModel, "unified_carrier_geometry");
  assert.equal(crossing.geometryModel, rope.geometryModel);
  assert.equal(crossing.crossSectionOrder, rope.crossSectionOrder);
  assert.equal(rope.beautySurfaceModel, "continuous_outward_lenticular_tow_shell");
  assert.equal(rope.closedPlasticSidewalls, false);
  assert.equal(rope.towEdgeModel, "rounded_down_outer_shell_edge");
  assert.equal(rope.towEdgeRollRatio, 0);
  assert.equal(crossing.contactInterpolation, rope.contactInterpolation);
  assert.equal(crossing.contactMaximumHeightCompression, rope.contactMaximumHeightCompression);
  assert.equal(crossing.contactFaceModel, "C2_finite_flat_contact_patch");
  assert.equal(crossing.contactClearanceMm, rope.contactClearanceMm);
  assert.equal(crossing.yarnWidth, rope.yarnWidth);
  assert.equal(crossing.yarnThickness, rope.yarnThickness);
  assert.equal(
    crossing.derivedDimensions.eventSpacingAxialMm,
    rope.derivedDimensions.eventSpacingAxialMm
  );
  assert.equal(
    crossing.derivedDimensions.contactHalfLengthAxialMm,
    rope.derivedDimensions.contactHalfLengthAxialMm
  );
  assert.deepEqual(crossing.derivedDimensions, rope.derivedDimensions);
  assert.equal(crossing.mode, "crossing");
  assert.equal(crossing.surfacePieceCount, 2);
  assert.equal(crossing.crossingSource, "cropped_from_full_rope_topology");
  assert.equal(crossing.topologySource, rope.topologySource);
  assert.equal(crossing.crossSectionFrameModel, rope.crossSectionFrameModel);
  assert.equal(rope.crossingDeformationModel, "continuous_across_width_saddle_field");
  assert.equal(rope.crossingEdgeTimingModel, "exact_unwrapped_line_intersection");
  assert.equal(crossing.ringSegments, rope.ringSegments);
  assert.ok(crossing.yarns[0].mesh.pathLengthMm > 0);
  assert.ok(rope.yarns[0].mesh.pathLengthMm > crossing.yarns[0].mesh.pathLengthMm);
  assert.deepEqual(crossing.yarns[0].crossingEvents, rope.yarns[0].crossingEvents);
  assert.deepEqual(crossing.yarns[1].crossingEvents, rope.yarns[1].crossingEvents);
  assert.equal(rope.mode, "rope");
  assert.equal(rope.surfacePieceCount, 16);
});

