test("polyester denier calibration reduces package area without changing topology", async () => {
  const [full, calibrated] = await Promise.all([
    runGeometry({ ...basePayload(), mode: "rope", denierScale: 1 }),
    runGeometry({ ...basePayload(), mode: "rope", denierScale: 0.7 })
  ]);

  assert.equal(calibrated.surfacePieceCount, full.surfacePieceCount);
  assert.ok(Math.abs(calibrated.derivedDimensions.polymerAreaMm2 / full.derivedDimensions.polymerAreaMm2 - 0.7) < 1e-9);
  assert.ok(calibrated.yarnThickness < full.yarnThickness);
});

test("denier and ends change tow mass and section without changing machine topology", async () => {
  const lowDenier = await runDimensions({ ...basePayload(), denier: 500 });
  const highDenier = await runDimensions({ ...basePayload(), denier: 1500 });
  const lowEnds = await runDimensions({ ...basePayload(), filamentCount: 12 });
  const highEnds = await runDimensions({ ...basePayload(), filamentCount: 35 });

  assert.ok(Math.abs(highDenier.polymerAreaMm2 / lowDenier.polymerAreaMm2 - 3) < 1e-9);
  assert.ok(Math.abs(
    highDenier.polymerAreaMm2
    - highDenier.effectiveCarrierDenier * 1000 / (9000 * 1380)
  ) < 1e-12);
  assert.ok(highDenier.thicknessMm > lowDenier.thicknessMm);
  assert.equal(highDenier.widthMm, lowDenier.widthMm);
  assert.ok(highDenier.equivalentEndDiameterMm > lowDenier.equivalentEndDiameterMm);

  assert.ok(Math.abs(highEnds.totalCarrierDenier / lowEnds.totalCarrierDenier - 35 / 12) < 1e-9);
  assert.ok(highEnds.thicknessMm > lowEnds.thicknessMm);
  assert.equal(highEnds.widthMm, lowEnds.widthMm);
});

